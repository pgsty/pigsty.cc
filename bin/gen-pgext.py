#!/usr/bin/env python3
"""Regenerate the compact landing-page catalog and its counts from pgext CSVs."""

import argparse
import csv
import hashlib
import io
import json
from datetime import datetime
from pathlib import Path
from urllib.request import urlopen
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = "TIME GIS RAG FTS OLAP FEAT LANG TYPE UTIL FUNC ADMIN STAT SEC FDW SIM ETL".split()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--src", type=Path, default=Path.home() / "pgsty/pgext/db")
    source.add_argument("--remote", action="store_true")
    parser.add_argument("--lang", choices=("zh", "en"), default="zh")
    args = parser.parse_args()
    day = datetime.now(ZoneInfo("Asia/Shanghai")).date().isoformat()
    tables, hashes = {}, {}
    for name in ("universe", "extension", "os", "pg"):
        if args.remote:
            with urlopen(f"https://raw.githubusercontent.com/pgsty/pgext/main/db/{name}.csv", timeout=30) as response:
                raw = response.read()
        else:
            raw = (args.src / f"{name}.csv").read_bytes()
        hashes[name] = hashlib.sha256(raw).hexdigest()
        tables[name] = list(csv.DictReader(io.StringIO(raw.decode("utf-8"))))

    packaged = {row["name"] for row in tables["extension"]}
    universe = tables["universe"]
    assert len({row["name"] for row in universe}) == len(universe), "duplicate extension name"
    assert packaged <= {row["name"] for row in universe}, "universe is missing packaged entries"
    assert {row["name"] for row in universe if row["packaged"] == "t"} == packaged, "catalog snapshots disagree"
    assert all(row["category"] in CATEGORIES for row in universe), "unknown category"
    rows = sorted(universe, key=lambda row: (CATEGORIES.index(row["category"]), -int(row["stars"] or 0), row["name"]))
    lines = [
        "# 首页扩展索引：由 bin/gen-pgext.py 从 pgext/db/universe.csv 生成。",
        f"# 生成日期 {day} · 共 {len(rows)} 个扩展，其中 {len(packaged)} 个已打包。",
        f"# universe.csv SHA-256: {hashes['universe']}",
        "# stars 为目录采集值，并非生成时对所有上游仓库重新抓取。",
    ]
    if args.lang == "en":
        lines = [
            "# Landing-page catalog generated by bin/gen-pgext.py from pgext/db/universe.csv.",
            f"# Generated {day}; {len(rows)} extensions, including {len(packaged)} packaged.",
            f"# universe.csv SHA-256: {hashes['universe']}",
            "# Stars come from the catalog snapshot, not a fresh query of every upstream repository.",
        ]
    for row in rows:
        data = dict(name=row["name"], cat=row["category"], pkg=row["name"] in packaged,
                    stars=int(row["stars"] or 0), desc=row[f"{args.lang}_desc"] or row["en_desc"])
        lines.append("- {" + ", ".join(
            f"{key}: {value if key == 'cat' else json.dumps(value, ensure_ascii=False)}"
            for key, value in data.items()
        ) + "}")
    (ROOT / "data/pgext/extension.yaml").write_text("\n".join(lines) + "\n")

    # Match pgext.summary in db/schema.sql: one lead extension per non-contrib package.
    packages = {row["pkg"] for row in tables["extension"] if row["lead"] == "t" and row["contrib"] != "t"}
    platforms = sum(row["active"] == "t" for row in tables["os"])
    majors = sum(row["active"] == "t" for row in tables["pg"])
    stats = [
        dict(label="内核分支", value=12, href="/docs/pgsql/kernel/"),
        dict(label="收录在册扩展", value=len(rows), href="https://pgext.cloud/"),
        dict(label="已打包扩展", value=len(packaged), href="https://pgext.cloud/?scope=packaged"),
        dict(label="扩展软件包", value=len(packages), href="https://pgext.cloud/?scope=packaged&entity=pkg", title="不含 contrib 的独立扩展包族，按主扩展去重"),
        dict(label="Linux 平台", value=platforms, href="https://pgext.cloud/list/os", title="操作系统大版本与 CPU 架构的组合"),
        dict(label="构建矩阵槽位", value=len(packages) * platforms * majors, href="https://pgext.cloud/matrix", title=f"{len(packages)} 包族 × {platforms} 平台 × {majors} PG 大版本，包含不适用及缺失组合"),
    ]
    header = [
        f"# bin/gen-pgext.py 生成，日期 {day}；来源 pgsty/pgext 的 db/*.csv。",
        "# 扩展软件包：lead 且非 contrib 的独立包族；Linux 平台：OS 大版本 × 架构。",
        f"# 矩阵槽位：{len(packages)} 包族 × {platforms} 平台 × {majors} PG 大版本；包含不适用与缺失组合，不代表已交付二进制包数。",
    ] + [f"# {name}.csv SHA-256: {digest}" for name, digest in hashes.items()]
    if args.lang == "en":
        labels = ["Kernel Forks", "Extensions Catalogued", "Packaged Extensions",
                  "Extension Packages", "Linux Platforms", "Build Matrix Slots"]
        for row, label in zip(stats, labels):
            row["label"] = label
        stats[3]["title"] = "Independent non-contrib package families, counted by lead extension"
        stats[4]["title"] = "Operating system major version and CPU architecture combinations"
        stats[5]["title"] = (
            f"{len(packages)} package families x {platforms} platforms x {majors} PG majors, "
            "including unavailable and inapplicable combinations"
        )
        header = [
            f"# Generated by bin/gen-pgext.py on {day} from pgsty/pgext db/*.csv.",
            "# Package families count non-contrib lead extensions; platforms are OS major x architecture.",
            f"# Matrix slots: {len(packages)} families x {platforms} platforms x {majors} PG majors.",
            "# Slots include unavailable and inapplicable combinations, not just published binaries.",
        ] + [f"# {name}.csv SHA-256: {digest}" for name, digest in hashes.items()]
    stat_lines = []
    for row in stats:
        for i, (key, value) in enumerate(row.items()):
            stat_lines.append(f"{'- ' if i == 0 else '  '}{key}: {value}")
    (ROOT / "data/pgext/stats.yaml").write_text("\n".join(header + stat_lines) + "\n")
    print(f"{len(rows)} catalogued; {len(packaged)} packaged; {len(packages)} package families; {platforms} platforms; {majors} PG majors")


if __name__ == "__main__":
    main()
